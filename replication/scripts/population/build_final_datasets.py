#!/usr/bin/env python3
"""
Build person_level.csv -- the canonical 1019-person population (910 original
hand-researched people + 109 added by the 2026-09 completeness check) -- from
the Senate and House biographical source files, joined against
billcount_FINAL.csv for federal sponsored-bill counts.

INPUTS (relative paths, run from the repo root):
    replication/data/source/senate/senators_A.csv, senators_B.csv, senators_C.csv,
        senate_batch2_completeness_gap.csv, senate_batch3_completeness_gap2.csv,
        senate_batch4_chamber_gap.csv (chamber service missing from the original research)
    replication/data/source/house/house_batch1_group1.csv, ... (16 files, see HOUSE_FILES below;
        batch6-7 are the completeness-gap additions, batch8 adds missing chamber service)
    billcount_FINAL.csv

These are original research data (Wikipedia-verified biographical records),
not an API cache -- they can't be regenerated by rerunning a script with a
key, so they're tracked in git rather than gitignored like data/raw/.

OUTPUT:
    person_level.csv

USAGE:
    python3 build_final_datasets.py
    (pass --senate-dir / --house-dir / --billcount to override the defaults
    below if your source files live somewhere else)
"""

import argparse
import csv
import os
from collections import defaultdict


def load(f):
    with open(f, newline='', encoding='utf-8') as fh:
        return list(csv.DictReader(fh))


HOUSE_FIELDS = ['Name', 'State', 'District', 'StateLegChamber', 'StateLegYears', 'StateLegTerms',
                'HouseYears', 'HouseCongresses', 'HouseTerms', 'BillsIntroducedHouse',
                'BillsIntroducedStateLeg', 'Notes/Sources']
NCOL = len(HOUSE_FIELDS)

HOUSE_FILES = [
    'house_batch1_group1.csv', 'house_batch1_california.csv', 'house_batch1_group3.csv',
    'house_batch2_groupA.csv', 'house_batch2_groupB.csv', 'house_batch2_groupC.csv',
    'house_batch3_groupA.csv', 'house_batch3_groupB.csv', 'house_batch3_groupC.csv',
    'house_batch4_FINAL.csv',
    'house_batch5_texas.csv', 'house_batch5_groupB.csv', 'house_batch5_groupC.csv',
    'house_batch6_completeness_gap.csv', 'house_batch7_completeness_gap2.csv',
    'house_batch8_chamber_gap.csv',
]

STATE_FIX = {'OH': 'Ohio', 'PA': 'Pennsylvania', 'RI': 'Rhode Island',
             'NC': 'North Carolina', 'NY': 'New York', 'OR': 'Oregon'}


def load_repair(f):
    """House files can have overflow commas in the free-text Notes/Sources
    column that break naive CSV parsing -- repair by re-joining anything
    past the last real column back into one field."""
    rows = []
    with open(f, newline='', encoding='utf-8') as fh:
        reader = csv.reader(fh)
        next(reader)  # header
        for raw in reader:
            if len(raw) < NCOL:
                raw = raw + [''] * (NCOL - len(raw))
            elif len(raw) > NCOL:
                head = raw[:NCOL - 1]
                tail = ','.join(raw[NCOL - 1:])
                raw = head + [tail]
            rows.append(dict(zip(HOUSE_FIELDS, raw)))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--senate-dir', default='replication/data/source/senate')
    ap.add_argument('--house-dir', default='replication/data/source/house')
    ap.add_argument('--billcount', default='replication/data/population/billcount_FINAL.csv')
    ap.add_argument('--out', default='replication/data/population/person_level.csv')
    args = ap.parse_args()

    for path, label in [(args.senate_dir, '--senate-dir'), (args.house_dir, '--house-dir')]:
        if not os.path.isdir(path):
            raise SystemExit(f"ERROR: {label} folder not found: {path}\n"
                              f"(run this from the repo root, or pass the correct path)")
    if not os.path.exists(args.billcount):
        raise SystemExit(f"ERROR: billcount file not found: {args.billcount}\n"
                          f"(pass --billcount /path/to/billcount_FINAL.csv)")

    # ---------- billcount lookup: (Name,State,Chamber) -> BioguideId ----------
    bc_rows = load(args.billcount)
    bg_lookup = {}
    for r in bc_rows:
        bg_lookup[(r['Name'], r['State'], r['Chamber'])] = r['BioguideId']

    # ---------- Load Senate ----------
    sen_rows = []
    for fname in ['senators_A.csv', 'senators_B.csv', 'senators_C.csv', 'senate_batch2_completeness_gap.csv', 'senate_batch3_completeness_gap2.csv',
                  'senate_batch4_chamber_gap.csv']:
        sen_rows.extend(load(os.path.join(args.senate_dir, fname)))
    for r in sen_rows:
        r['BioguideId'] = bg_lookup.get((r['Name'], r['State'], 'Senate'), '')

    # ---------- Load House (repair overflow commas) ----------
    house_rows = []
    for fname in HOUSE_FILES:
        rows = load_repair(os.path.join(args.house_dir, fname))
        for r in rows:
            if r['State'] in STATE_FIX:
                r['State'] = STATE_FIX[r['State']]
        house_rows.extend(rows)
    for r in house_rows:
        r['BioguideId'] = bg_lookup.get((r['Name'], r['State'], 'House'), '')

    print('Senate rows:', len(sen_rows), '| House rows:', len(house_rows))
    missing_bg = [r for r in sen_rows + house_rows if not r['BioguideId']]
    print('Rows with no BioguideId (should be 0):', len(missing_bg))

    # ---------- Build person-level table keyed by BioguideId ----------
    sen_by_bg = defaultdict(list)
    for r in sen_rows:
        sen_by_bg[r['BioguideId']].append(r)
    house_by_bg = defaultdict(list)
    for r in house_rows:
        house_by_bg[r['BioguideId']].append(r)

    # TotalSponsoredItems per bioguide (same figure regardless of chamber row, since it's a career total)
    bc_by_bg = {}
    for r in bc_rows:
        if r['TotalSponsoredItems'].isdigit():
            bc_by_bg[r['BioguideId']] = int(r['TotalSponsoredItems'])

    all_bg = sorted(set(sen_by_bg) | set(house_by_bg))
    print('Unique BioguideIds (people):', len(all_bg))

    PERSON_FIELDS = [
        'BioguideId', 'Name', 'State', 'Chambers',
        'StateLegChamber', 'StateLegYears', 'StateLegTerms',
        'SenateYears', 'SenateCongresses', 'SenateTerms',
        'HouseYears', 'HouseCongresses', 'HouseTerms', 'District',
        'TotalSponsoredItems', 'BillsIntroducedStateLeg', 'Notes'
    ]
    person_rows = []
    for bg in all_bg:
        srow = sen_by_bg[bg][0] if bg in sen_by_bg else None
        hrow = house_by_bg[bg][0] if bg in house_by_bg else None
        chambers = []
        if srow:
            chambers.append('Senate')
        if hrow:
            chambers.append('House')
        # Prefer the Senate-listed name/state as canonical when both exist (matches this project's earlier convention)
        name = (srow or hrow)['Name']
        state = (srow or hrow)['State']
        stateleg_chamber = (srow or {}).get('StateLegChamber') or (hrow or {}).get('StateLegChamber') or ''
        stateleg_years = (srow or {}).get('StateLegYears') or (hrow or {}).get('StateLegYears') or ''
        stateleg_terms = (srow or {}).get('StateLegTerms') or (hrow or {}).get('StateLegTerms') or ''
        stateleg_bills = (srow or {}).get('BillsIntroducedStateLeg') or (hrow or {}).get('BillsIntroducedStateLeg') or ''
        notes_parts = []
        if srow:
            notes_parts.append('Senate record: ' + srow.get('Notes/Sources', ''))
        if hrow:
            notes_parts.append('House record: ' + hrow.get('Notes/Sources', ''))
        person_rows.append({
            'BioguideId': bg, 'Name': name, 'State': state, 'Chambers': '+'.join(chambers),
            'StateLegChamber': stateleg_chamber, 'StateLegYears': stateleg_years, 'StateLegTerms': stateleg_terms,
            'SenateYears': (srow or {}).get('SenateYears', ''), 'SenateCongresses': (srow or {}).get('SenateCongresses', ''),
            'SenateTerms': (srow or {}).get('SenateTerms', ''),
            'HouseYears': (hrow or {}).get('HouseYears', ''), 'HouseCongresses': (hrow or {}).get('HouseCongresses', ''),
            'HouseTerms': (hrow or {}).get('HouseTerms', ''), 'District': (hrow or {}).get('District', ''),
            'TotalSponsoredItems': bc_by_bg.get(bg, ''),
            'BillsIntroducedStateLeg': stateleg_bills,
            'Notes': ' || '.join(notes_parts),
        })

    with open(args.out, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=PERSON_FIELDS)
        w.writeheader()
        w.writerows(person_rows)

    print(f'Wrote {args.out}:', len(person_rows), 'rows')

    both_chamber_count = sum(1 for r in person_rows if r['Chambers'] == 'Senate+House')
    print('Both-chamber individuals:', both_chamber_count)


if __name__ == '__main__':
    main()
